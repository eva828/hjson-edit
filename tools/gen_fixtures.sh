#!/usr/bin/env bash
# 期待値（fixtures）を hjson-cs の実行結果から再生成する。
# 必要なもの: nix（dotnet SDK の取得）、git、ネットワーク。
set -euo pipefail
cd "$(dirname "$0")/.."

WORK="$(tools/cs-oracle/build.sh)" || exit 1
. tools/cs-oracle/reference.env

ORACLE_DLL="tools/cs-oracle/bin/Release/net10.0/Oracle.dll"
FIXTURES="tests/fixtures/hjson-cs"
REPO_ROOT="$(pwd)"
echo "== オラクルを実行（cases / assets）"
nix --extra-experimental-features 'nix-command flakes' --option sandbox false \
  shell "$DOTNET_ATTR" -c bash -c "
    set -euo pipefail
    export DOTNET_CLI_HOME=\${DOTNET_CLI_HOME:-/tmp/dotnethome}
    export NUGET_PACKAGES=\${NUGET_PACKAGES:-/tmp/nuget}
    export DOTNET_NOLOGO=1
    dotnet '$REPO_ROOT/$ORACLE_DLL' cases '$REPO_ROOT/$FIXTURES/inputs.tsv' > /tmp/cs-oracle-cases.tsv
    dotnet '$REPO_ROOT/$ORACLE_DLL' assets '$WORK/test/assets' > /tmp/cs-oracle-assets.tsv
  " 2>/dev/null

header() {
  echo "# generated by tools/gen_fixtures.sh"
  echo "# reference: $HJSON_CS_REPO @ $HJSON_CS_COMMIT ($HJSON_CS_VERSION, net10.0)"
  echo "# sdk: $DOTNET_NAME ($DOTNET_SDK_VERSION)"
  echo "# format: id<TAB>status(OK|ERR)<TAB>value(正準形) | message"
}

{
  header
  echo "# input: tests/fixtures/hjson-cs/inputs.tsv"
  grep -v '^#' /tmp/cs-oracle-cases.tsv
} > "$FIXTURES/cases.tsv"

{
  header
  echo "# input: hjson-cs $HJSON_CS_COMMIT test/assets/*_test.{hjson,json}"
  grep -v '^#' /tmp/cs-oracle-assets.tsv
} > "$FIXTURES/assets_cs.tsv"

echo "== 生成完了"
wc -l "$FIXTURES/cases.tsv" "$FIXTURES/assets_cs.tsv"
